using System.Text;

namespace PSLDiscordBot.Analyzer.AsyncEventHelper;

[Generator]
public class AsyncEventGenerator : ISourceGenerator
{
	private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
		.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

	private static Accessibility ToAccessibility(object? enumValue)
	{
		return enumValue is int value and not (int)Accessibility.NotApplicable
			? (Accessibility)value
			: Accessibility.Private;
	}

	private static string ToHintName(IEventSymbol eventSymbol)
	{
		StringBuilder builder = new("AsyncEvent.");
		foreach (char c in $"{eventSymbol.ContainingType.ToDisplayString()}.{eventSymbol.Name}")
			builder.Append(char.IsLetterOrDigit(c) || c == '.' ? c : '_');
		return builder.Append(".g").ToString();
	}

	private static string GetTypeHeader(TypeDeclarationSyntax syntax)
	{
		string keyword = syntax.Keyword.Text;
		if (syntax is RecordDeclarationSyntax { ClassOrStructKeyword.RawKind: not 0 } record)
			keyword += " " + record.ClassOrStructKeyword.Text;
		// constraints may be omitted on the other partial declarations
		return $"{syntax.Modifiers} {keyword} {syntax.Identifier.Text}{syntax.TypeParameterList}";
	}

	public void Execute(GeneratorExecutionContext context)
	{
		Compilation compilation = context.Compilation;

		// without the attribute type nothing can be annotated
		if (compilation.GetTypeByMetadataName(typeof(GenerateAsyncEventAttribute).FullName) is null)
			return;
		INamedTypeSymbol eventHandlerSymbol = compilation.GetTypeByMetadataName(typeof(AsyncEventHandler<>).FullName)!;
		INamedTypeSymbol asyncEventsSymbol = compilation.GetTypeByMetadataName(typeof(AsyncEvents<>).FullName)!;

		foreach (SyntaxTree tree in compilation.SyntaxTrees)
		{
			SemanticModel semanticModel = compilation.GetSemanticModel(tree);

			foreach (EventFieldDeclarationSyntax @event in tree
				.GetRoot()
				.DescendantNodes()
				.OfType<EventFieldDeclarationSyntax>())
			{
				if (@event.AttributeLists.Count == 0) continue;

				VariableDeclaratorSyntax eventDeclarator = @event.Declaration.Variables[0];
				if (semanticModel.GetDeclaredSymbol(eventDeclarator) is not IEventSymbol eventSymbol) continue;

				AttributeData? attribute = PSLDiscordBotAnalyzer.GetAttributeOrDefault<GenerateAsyncEventAttribute>(eventSymbol, compilation);
				if (attribute is null) continue;

				if (@event.Declaration.Variables.Count != 1)
				{
					// every declarator would share the attribute, but each needs its own generated field
					context.ReportDiagnostic(Diagnostic.Create(PSLDiscordBotAnalyzer.MultipleEventFieldDefinitionRule, @event.GetLocation(), @event.Declaration.Variables.Count));
					continue;
				}

				if (eventSymbol.Type is not INamedTypeSymbol { IsGenericType: true } type
					|| !SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, eventHandlerSymbol))
				{
					context.ReportDiagnostic(Diagnostic.Create(PSLDiscordBotAnalyzer.BadAsyncEventDefinitionRule, @event.GetLocation()));
					continue;
				}

				// innermost first
				List<TypeDeclarationSyntax> containingSyntaxes = [.. @event.Ancestors().OfType<TypeDeclarationSyntax>()];
				if (!@event.Modifiers.Any(SyntaxKind.PartialKeyword))
				{
					context.ReportDiagnostic(Diagnostic.Create(PSLDiscordBotAnalyzer.MustBePartialRule, @event.GetLocation(), eventSymbol.Name));
					continue;
				}
				TypeDeclarationSyntax? notPartial = containingSyntaxes.FirstOrDefault(x => !x.Modifiers.Any(SyntaxKind.PartialKeyword));
				if (notPartial is not null)
				{
					context.ReportDiagnostic(Diagnostic.Create(PSLDiscordBotAnalyzer.MustBePartialRule, notPartial.Identifier.GetLocation(), notPartial.Identifier.Text));
					continue;
				}

				Accessibility accessibility = ToAccessibility(attribute.NamedArguments
					.FirstOrDefault(x => x.Key == nameof(GenerateAsyncEventAttribute.GeneratedFieldAccessibility)).Value.Value);
				string fieldName = attribute.NamedArguments
					.FirstOrDefault(x => x.Key == nameof(GenerateAsyncEventAttribute.GeneratedFieldName)).Value.Value as string
					?? $"_asyncEvent_{eventSymbol.Name}";

				StringBuilder generatedClass = new();
				generatedClass.AppendLine("// <auto-generated/>");
				generatedClass.AppendLine("#nullable enable");
				generatedClass.AppendLine();

				INamespaceSymbol containingNamespace = eventSymbol.ContainingType.ContainingNamespace;
				if (!containingNamespace.IsGlobalNamespace)
				{
					generatedClass.AppendLine($"namespace {containingNamespace.ToDisplayString()};");
					generatedClass.AppendLine();
				}

				for (int i = containingSyntaxes.Count - 1; i >= 0; i--)
				{
					generatedClass.AppendLine(GetTypeHeader(containingSyntaxes[i]));
					generatedClass.AppendLine("{");
				}

				string fieldType = asyncEventsSymbol.Construct([.. type.TypeArguments]).ToDisplayString(TypeFormat);
				string fieldModifiers = $"{SyntaxFacts.GetText(accessibility)} {(eventSymbol.IsStatic ? "static " : "")}readonly".Trim();
				generatedClass.AppendLine($$"""
					[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]
					{{fieldModifiers}} {{fieldType}} {{fieldName}} = new();

					{{@event.Modifiers}} event {{type.ToDisplayString(TypeFormat)}} {{eventSymbol.Name}}
					{
						add
						{
							if (value is not null)
								{{fieldName}}.Append(value);
						}
						remove
						{
							if (value is not null)
								{{fieldName}}.Remove(value);
						}
					}
					""");

				generatedClass.Append('}', containingSyntaxes.Count);

				context.AddSource(ToHintName(eventSymbol), SourceText.From(generatedClass.ToString(), Encoding.UTF8));
			}
		}
	}

	public void Initialize(GeneratorInitializationContext context)
	{
#if SOURCEGENDEBUG
		if (!System.Diagnostics.Debugger.IsAttached)
		{
			System.Diagnostics.Debugger.Launch();
		}
#endif
	}
}
